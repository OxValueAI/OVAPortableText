export type EditorMessageKey = keyof typeof UI_TEXT.en;
export type EditorMessages = Record<EditorMessageKey, string>;

export function detectInitialLocale(locale?: EditorLocale): EditorLocale {
  if (locale) {
    return locale;
  }
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")) {
    return "zh";
  }
  return "en";
}
